/*
    Problem: 630A - Again Twenty Five!
    Platform: Codeforces
    Difficulty: 800

    Approach:
    - For every n >= 2, the last two digits of 5^n are always 25.
    - Therefore, simply print 25.

    Time Complexity: O(1)
    Space Complexity: O(1)
*/

#include <bits/stdc++.h>
using namespace std;

int main() {
    unsigned long long n;
    cin >> n;

    cout << 25 << '\n';

    return 0;
}
